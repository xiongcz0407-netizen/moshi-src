# 设计 107：铁匠的 3 个动作。度数：X 往前抬 / 往前弯，Z 往侧面歪（竖着的骨头），Y 扭转
UP = {'Spine': (10, 0, 4), 'Chest': (4, 0, 0), 'Head': (10, 0, 0), 'R_Arm': (80, 0, -18), 'R_ForeArm': (75, 0, 0), 'R_Hand': (20, 0, 0),
      'L_Arm': (35, 0, 8), 'L_ForeArm': (45, 0, 0), 'L_Hand': (0, 0, 0)}
HIT = {**UP, 'Spine': (16, 0, 4), 'Head': (16, 0, 0), 'R_Arm': (40, 0, -10), 'R_ForeArm': (25, 0, 0), 'R_Hand': (-10, 0, 0)}
MID = {**UP, 'R_Arm': (95, 0, -18), 'R_ForeArm': (95, 0, 0)}
# 待机敲铁砧：1.6 秒一下（举起 → 停一下 → 砸下去 → 停在砧上 → 慢慢抬起）
make('idle', 1.6, [(0.0, UP), (0.35, MID), (0.55, MID), (0.72, HIT), (0.86, HIT), (1.3, UP)])
# 擦汗：放下锤子的手、左手抬到额头抹一下，再回到准备敲的姿势
BROW = {**UP, 'Spine': (2, 0, 0), 'Head': (-12, 0, 0), 'R_Arm': (10, 0, -6), 'R_ForeArm': (20, 0, 0), 'L_Arm': (95, 0, -20), 'L_ForeArm': (125, 0, 0), 'L_Hand': (10, 0, 0)}
BROW2 = {**BROW, 'L_Arm': (100, 0, 10), 'Head': (-14, 0, -6)}
make('wipe', 3.0, [(0.0, UP), (0.6, BROW), (1.3, BROW2), (1.8, BROW), (2.4, {**BROW, 'L_Arm': (40, 0, 8), 'L_ForeArm': (40, 0, 0)}), (3.0, UP)], loop=False)
# 挥手招呼：右手举过头、小臂左右摆 3 下
WV = {**UP, 'Spine': (-4, 0, 6), 'Head': (0, 0, 4), 'R_Arm': (150, 0, 40), 'R_ForeArm': (10, 0, 30), 'R_Hand': (0, 0, 0), 'L_Arm': (5, 0, 4), 'L_ForeArm': (15, 0, 0)}
WV2 = {**WV, 'R_ForeArm': (10, 0, -20)}
make('wave', 2.0, [(0.0, UP), (0.4, WV), (0.65, WV2), (0.9, WV), (1.15, WV2), (1.4, WV), (2.0, UP)], loop=False)
